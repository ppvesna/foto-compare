import 'dart:math' as math;

import 'package:flutter/material.dart';

/// Compact 5×7 Cyrillic display text for the comparison HUD.
///
/// It is painted from rectangles instead of a platform font, so glyphs keep
/// the same square construction in every browser. Unsupported glyphs use a
/// small outlined placeholder rather than silently changing font.
class PixelText extends StatelessWidget {
  final String text;
  final Color color;
  // A one-pixel block shadow keeps the HUD readable over detailed images.
  final Color shadowColor;
  final double pixelSize;
  final bool uppercase;

  const PixelText({
    super.key,
    required this.text,
    required this.color,
    this.shadowColor = const Color(0xB8000000),
    this.pixelSize = 1.5,
    this.uppercase = true,
  });

  @override
  Widget build(BuildContext context) {
    final normalized = (uppercase ? text.toUpperCase() : text)
        .replaceAll('…', '...')
        .replaceAll('—', '-')
        .replaceAll('–', '-');
    return LayoutBuilder(
      builder: (context, constraints) {
        final naturalUnits = _measureUnits(normalized);
        final maxWidth = constraints.maxWidth.isFinite
            ? constraints.maxWidth
            : naturalUnits * pixelSize;
        final scale = naturalUnits <= 0
            ? pixelSize
            : math.min(pixelSize, maxWidth / naturalUnits);
        final width = math.min(maxWidth, naturalUnits * scale);
        return Semantics(
          label: normalized,
          child: SizedBox(
            width: width,
            height: 8 * scale,
            child: CustomPaint(
              painter: _PixelTextPainter(
                text: normalized,
                color: color,
                shadowColor: shadowColor,
                pixelSize: scale,
              ),
            ),
          ),
        );
      },
    );
  }
}

double _measureUnits(String text) {
  if (text.isEmpty) return 0;
  var width = 0.0;
  for (final rune in text.runes) {
    width += _glyphWidth(String.fromCharCode(rune)) + 1;
  }
  return width - 1;
}

int _glyphWidth(String character) => character == ' ' ? 3 : 5;

class _PixelTextPainter extends CustomPainter {
  final String text;
  final Color color;
  final Color shadowColor;
  final double pixelSize;

  const _PixelTextPainter({
    required this.text,
    required this.color,
    required this.shadowColor,
    required this.pixelSize,
  });

  @override
  void paint(Canvas canvas, Size size) {
    final foregroundPaint = Paint()
      ..color = color
      ..isAntiAlias = false;
    final shadowPaint = Paint()
      ..color = shadowColor
      ..isAntiAlias = false;
    var x = 0.0;
    for (final rune in text.runes) {
      final character = String.fromCharCode(rune);
      final glyph = _glyphs[character] ?? _glyphs['?']!;
      if (shadowColor.alpha != 0) {
        _paintGlyph(
          canvas,
          glyph,
          Offset(x + 1, 1),
          pixelSize,
          shadowPaint,
        );
      }
      _paintGlyph(canvas, glyph, Offset(x, 0), pixelSize, foregroundPaint);
      x += (_glyphWidth(character) + 1) * pixelSize;
      if (x > size.width) break;
    }
  }

  void _paintGlyph(
    Canvas canvas,
    List<String> glyph,
    Offset origin,
    double scale,
    Paint paint,
  ) {
    for (var row = 0; row < glyph.length; row++) {
      for (var column = 0; column < glyph[row].length; column++) {
        if (glyph[row][column] != '1') continue;
        canvas.drawRect(
          Rect.fromLTWH(
            origin.dx + column * scale,
            origin.dy + row * scale,
            scale,
            scale,
          ),
          paint,
        );
      }
    }
  }

  @override
  bool shouldRepaint(covariant _PixelTextPainter oldDelegate) =>
      oldDelegate.text != text ||
      oldDelegate.color != color ||
      oldDelegate.shadowColor != shadowColor ||
      oldDelegate.pixelSize != pixelSize;
}

